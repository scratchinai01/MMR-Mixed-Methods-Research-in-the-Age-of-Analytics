// 迴歸結果的白話解讀：依當天的係數方向與 p 值自動產生，上台可以直接照著講
// 結果變數 SCAR＝新聞日後 5 個交易日「比大盤（0050）多漲或少漲多少」，單位是「平常 5 日波動的幾倍」
// =====================================================================

export const VAR_ZH: Record<string, string> = {
  Prior_SCAR: '新聞前 5 天的表現',
  Size: '公司規模（市值）',
  Positive: '當天的正面新聞比例',
  Negative: '當天的負面新聞比例',
  PE_ratio: '本益比',
  Sales_growth: '營收成長率',
  MB_ratio: '股價淨值比',
};

const fmt = (x: number) => (Math.abs(x) < 0.01 ? x.toFixed(3) : x.toFixed(2));

/** 一個變數（或交互作用項）的白話解讀 */
export function plainFor(term: string, coef: number, p: number, paperSign?: number): string {
  const sig = p < 0.05;
  const near = !sig && p < 0.1;
  const dirWord = coef > 0 ? '正' : '負';

  // 交互作用項：X × S
  if (term.includes(' X ')) {
    const [x, s] = term.split(' X ');
    const X = VAR_ZH[x] || x;
    const S = s === 'Positive' ? '正面' : '負面';
    if (!sig) {
      return `${X}高或低，${S}新聞之後的表現看不出明確差別${near ? `（方向為${dirWord}，接近顯著，只能算初步跡象）` : ''}。`;
    }
    let t: string;
    if (s === 'Positive') {
      t = coef < 0 ? `${X}越高，正面新聞帶來的好處越小。` : `${X}越高，正面新聞帶來的好處越大。`;
    } else {
      t = coef < 0 ? `${X}越高，負面新聞之後的表現越差。` : `${X}越高，負面新聞之後的表現越好（傷害較小或反彈較大）。`;
    }
    if (term === 'Sales_growth X Positive') {
      t += '這就是原著最重要的「正面情緒效果遞減」';
      if (paperSign !== undefined) t += Math.sign(coef) === Math.sign(paperSign) ? '，方向與原著一致。' : '，但方向與原著相反。';
      else t += '。';
    }
    return t;
  }

  const X = VAR_ZH[term] || term;
  if (!sig) {
    return `看不出${X}和新聞後表現有明確關係${near ? `（方向為${dirWord}，接近顯著，只能算初步跡象）` : '（可能只是巧合）'}。`;
  }
  switch (term) {
    case 'Positive':
      return coef > 0
        ? `正面新聞越多的日子，之後 5 天比大盤表現越好。一天的新聞若從全是中性變成全是正面，約多出平常 5 日波動的 ${fmt(coef)} 倍；正面比例每多 10 個百分點，約多 ${fmt(coef * 0.1)} 倍。`
        : '正面新聞越多的日子，之後 5 天反而比大盤差，與直覺相反，解讀要保守。';
    case 'Negative':
      return coef > 0
        ? '與直覺相反：負面新聞越多的日子，之後 5 天反而比大盤好。可能是負面消息當天就已跌完、之後反彈（日資料看不到當天盤中），解讀要保守。'
        : '負面新聞越多的日子，之後 5 天比大盤表現越差，符合直覺。';
    case 'Prior_SCAR':
      return coef < 0 ? '新聞前幾天漲多的股票，之後傾向回落（反轉）。' : '新聞前幾天漲多的股票，之後傾向繼續漲（延續）。';
    default:
      return coef > 0 ? `${X}越高，新聞後 5 天比大盤表現越好。` : `${X}越高，新聞後 5 天比大盤表現越差。`;
  }
}

