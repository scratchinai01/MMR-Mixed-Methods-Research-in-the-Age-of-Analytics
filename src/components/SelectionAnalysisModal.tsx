import React, { useState, useEffect, useRef } from 'react';
import { 
  X, 
  Sparkles, 
  Volume2, 
  VolumeX, 
  Copy, 
  Check, 
  BookOpen, 
  Globe, 
  Zap, 
  Send, 
  MessageSquarePlus, 
  RefreshCw, 
  Sigma,
  HelpCircle,
  Code,
  TrendingUp,
  AlertTriangle
} from 'lucide-react';
import { callAiApi } from '../services/aiHelper.ts';
import { saveFollowupToFirestore } from '../services/firebase.ts';
import { MathRenderer } from './MathRenderer.tsx';

interface SelectionAnalysisModalProps {
  isOpen: boolean;
  onClose: () => void;
  title: string;
  sourceText: string;
  analysisContent: string;
  loading: boolean;
  engineUsed?: string;
  latencyMs?: number;
  onSpeakText: (text: string) => void;
  isSpeaking: boolean;
  onStopSpeech: () => void;
}

export const SelectionAnalysisModal: React.FC<SelectionAnalysisModalProps> = ({
  isOpen,
  onClose,
  title,
  sourceText,
  analysisContent,
  loading,
  engineUsed,
  latencyMs,
  onSpeakText,
  isSpeaking,
  onStopSpeech,
}) => {
  const [copied, setCopied] = useState<boolean>(false);
  const [messages, setMessages] = useState<{ role: 'user' | 'ai'; text: string; modelUsed?: string }[]>([]);
  const [followupInput, setFollowupInput] = useState<string>('');
  const [relayLoading, setRelayLoading] = useState<boolean>(false);
  const [questionsLoading, setQuestionsLoading] = useState<boolean>(false);

  // In-modal text selection state for continuous speech and quote-ask
  const [modalSelectedText, setModalSelectedText] = useState<string>('');
  const [modalSelectionPos, setModalSelectionPos] = useState<{ x: number; y: number } | null>(null);
  const [copiedSelection, setCopiedSelection] = useState<boolean>(false);

  const modalBodyRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  // Stage progression state
  const [currentStage, setCurrentStage] = useState<number>(1);
  const [stageTitle, setStageTitle] = useState<string>('階段 1：核心概念解構與資料取得');

  // Exactly 4 dynamic stage questions generated by AI
  const [dynamicRelayQuestions, setDynamicRelayQuestions] = useState<string[]>([
    '🔬 階段 2：GEE 廣義估計方程式中工作相關矩陣 AR(1) 與 Exchangeable 的 QIC 檢定標準？',
    '📐 階段 2：連續變數 Mean-Centering 中心化消除交互作用項共線性之數學證明？',
    '📊 階段 2：Loughran-McDonald (LM) 財經情緒詞庫在非英語市場（如台股）的在地化偏誤校正？',
    '🛡️ 階段 2：如何用固定效果 (Fixed Effects) 與動態面板 GMM 排除未觀察企業異質性？'
  ]);

  // Handle in-modal text selection for continuous speech & question asking
  useEffect(() => {
    if (!isOpen) return;

    const handleMouseUp = () => {
      setTimeout(() => {
        const selection = window.getSelection();
        if (!selection || selection.isCollapsed) {
          return;
        }

        const text = selection.toString().trim();
        if (text.length < 2) {
          setModalSelectedText('');
          setModalSelectionPos(null);
          return;
        }

        try {
          const range = selection.getRangeAt(0);
          const rect = range.getBoundingClientRect();
          if (rect.width < 5 || rect.height < 5) return;

          // Check if selection is inside our modal body
          if (modalBodyRef.current && modalBodyRef.current.contains(range.commonAncestorContainer)) {
            setModalSelectedText(text);
            setModalSelectionPos({
              x: Math.max(10, rect.left + rect.width / 2),
              y: Math.max(10, rect.top - 10)
            });
          }
        } catch (e) {
          console.warn('In-modal selection error:', e);
        }
      }, 100);
    };

    const handleMouseDown = (e: MouseEvent) => {
      const target = e.target as HTMLElement;
      if (!target.closest('#in-modal-selection-popover')) {
        setTimeout(() => {
          const sel = window.getSelection();
          if (!sel || sel.isCollapsed) {
            setModalSelectedText('');
            setModalSelectionPos(null);
          }
        }, 150);
      }
    };

    document.addEventListener('mouseup', handleMouseUp);
    document.addEventListener('mousedown', handleMouseDown);

    return () => {
      document.removeEventListener('mouseup', handleMouseUp);
      document.removeEventListener('mousedown', handleMouseDown);
    };
  }, [isOpen]);

  // Stage-by-stage dynamic 4-question generator using Gemini AI
  const fetchDynamicQuestions = async (targetStage: number, lastQ?: string, lastAns?: string) => {
    setQuestionsLoading(true);
    try {
      const res = await callAiApi('/api/ai/dynamic-questions', {
        stage: targetStage,
        currentTopic: title,
        lastQuery: lastQ || (messages[messages.length - 1]?.text) || title,
        lastAnswer: lastAns || analysisContent,
        sourceText: sourceText,
      });

      if (res && res.success && Array.isArray(res.questions) && res.questions.length >= 4) {
        setDynamicRelayQuestions(res.questions.slice(0, 4));
        if (res.stage) setCurrentStage(res.stage);
        if (res.stageTitle) setStageTitle(res.stageTitle);
        return;
      }
    } catch (err) {
      console.warn('Failed to fetch dynamic questions:', err);
    } finally {
      setQuestionsLoading(false);
    }
  };

  useEffect(() => {
    if (analysisContent) {
      setMessages([
        { role: 'ai', text: analysisContent, modelUsed: engineUsed }
      ]);
      fetchDynamicQuestions(1, title, analysisContent);
    }
  }, [analysisContent, engineUsed, title]);

  if (!isOpen) return null;

  const handleCopy = (text: string) => {
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleSpeakSelectedSnippet = (textToSpeak: string) => {
    if (isSpeaking) {
      onStopSpeech();
    }
    onSpeakText(textToSpeak);
  };

  const handleQuoteSelectedTextInInput = (quote: string) => {
    setFollowupInput(`針對這段文字「${quote.slice(0, 120)}${quote.length > 120 ? '...' : ''}」，請問：`);
    setModalSelectedText('');
    setModalSelectionPos(null);
    if (inputRef.current) {
      inputRef.current.focus();
    }
  };

  const handleSendRelay = async (queryText?: string) => {
    const promptText = queryText || followupInput;
    if (!promptText.trim() || relayLoading) return;

    const userQuery = promptText.trim();
    setMessages(prev => [...prev, { role: 'user', text: userQuery }]);
    setFollowupInput('');
    setRelayLoading(true);

    try {
      const conversationContext = messages.map(m => `${m.role === 'user' ? '用戶提問' : 'AI解析'}: ${m.text}`).join('\n\n');
      const data = await callAiApi('/api/gemini/explain', {
        question: userQuery,
        context: `針對先前討論之原文：「${sourceText}」\n\n【先前對話歷史紀錄】：\n${conversationContext.slice(-1500)}`,
        isFollowup: true,
      });

      const aiReply = data.answer || '接力解析完成。';
      const aiModel = data.modelUsed || 'Gemini 2.5 Flash';

      setMessages(prev => [
        ...prev,
        { role: 'ai', text: aiReply, modelUsed: aiModel }
      ]);

      // Record follow-up QA dialogue in Firebase Firestore
      saveFollowupToFirestore({
        sourceModule: 'selection_analysis',
        topic: title,
        sourceText: sourceText.slice(0, 500),
        question: userQuery,
        answer: aiReply,
        modelUsed: aiModel,
        stage: currentStage,
      }).catch(err => console.warn('Firestore followup save warning:', err));

      fetchDynamicQuestions(currentStage, userQuery, aiReply);
    } catch (err: any) {
      setMessages(prev => [
        ...prev,
        { role: 'ai', text: `接力探討發生錯誤：${err.message}` }
      ]);
    } finally {
      setRelayLoading(false);
    }
  };

  const handleRegenerateCurrentStageQuestions = () => {
    const lastUser = [...messages].reverse().find(m => m.role === 'user')?.text || title;
    const lastAi = [...messages].reverse().find(m => m.role === 'ai')?.text || analysisContent;
    fetchDynamicQuestions(Math.max(1, currentStage - 1), lastUser, lastAi);
  };

  const handleAdvanceToNextStage = () => {
    const lastUser = [...messages].reverse().find(m => m.role === 'user')?.text || title;
    const lastAi = [...messages].reverse().find(m => m.role === 'ai')?.text || analysisContent;
    fetchDynamicQuestions(currentStage, lastUser, lastAi);
  };

  // Helper to render inline markdown & Math equations
  const renderInlineMathAndMarkdown = (text: string) => {
    if (!text) return null;
    const parts = text.split(/(\*\*.*?\*\*|`.*?`|\$\$.*?\$\$|\$.*?\$|\\\[.*?\\\]|\\\(.*?\\\))/g);
    return parts.map((part, pIdx) => {
      if (!part) return null;
      if (part.startsWith('**') && part.endsWith('**')) {
        return <strong key={pIdx} className="font-extrabold text-slate-900 bg-amber-100/60 px-1 py-0.5 rounded">{part.slice(2, -2)}</strong>;
      }
      if (part.startsWith('`') && part.endsWith('`')) {
        return <code key={pIdx} className="px-1.5 py-0.5 rounded bg-slate-100 font-mono text-[11px] font-bold text-indigo-700 border border-slate-200">{part.slice(1, -1)}</code>;
      }
      if ((part.startsWith('$$') && part.endsWith('$$')) || (part.startsWith('\\[') && part.endsWith('\\]'))) {
        const mathContent = part.replace(/^(\$\$|\\\[)|(\$\$|\\\])$/g, '').trim();
        return <MathRenderer key={pIdx} math={mathContent} displayMode={true} />;
      }
      if ((part.startsWith('$') && part.endsWith('$')) || (part.startsWith('\\(') && part.endsWith('\\)'))) {
        const mathContent = part.replace(/^(\$|\\\()|(\$|\\\))$/g, '').trim();
        return <MathRenderer key={pIdx} math={mathContent} displayMode={false} />;
      }
      return part;
    });
  };

  const renderMarkdown = (content: string) => {
    if (!content) return null;
    const lines = content.split('\n');
    return lines.map((line, idx) => {
      const trimmed = line.trim();
      if (trimmed.startsWith('$$') && trimmed.endsWith('$$') && trimmed.length > 4) {
        return <MathRenderer key={idx} math={trimmed.slice(2, -2)} displayMode={true} />;
      }
      if (trimmed.startsWith('### ') || trimmed.startsWith('#### ')) {
        return (
          <h4 key={idx} className="font-bold text-indigo-950 text-base sm:text-lg mt-4 mb-2 flex items-center gap-2">
            <span className="w-1.5 h-4 bg-indigo-600 rounded-full" />
            <span>{renderInlineMathAndMarkdown(trimmed.replace(/^#+\s*/, ''))}</span>
          </h4>
        );
      }
      if (trimmed.startsWith('## ')) {
        return (
          <h3 key={idx} className="font-bold text-slate-900 text-lg sm:text-xl mt-5 mb-3 border-b border-indigo-200 pb-1.5">
            {renderInlineMathAndMarkdown(trimmed.replace(/^#+\s*/, ''))}
          </h3>
        );
      }
      if (trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
        return (
          <li key={idx} className="ml-5 list-disc my-1 text-slate-700 leading-relaxed">
            {renderInlineMathAndMarkdown(trimmed.replace(/^[-*]\s+/, ''))}
          </li>
        );
      }
      if (/^\d+\.\s+/.test(trimmed)) {
        const numMatch = trimmed.match(/^(\d+)\.\s+(.*)/);
        if (numMatch) {
          return (
            <div key={idx} className="my-1.5 pl-2 text-slate-700 flex items-start gap-2">
              <span className="font-bold text-indigo-700 shrink-0">{numMatch[1]}.</span>
              <div>{renderInlineMathAndMarkdown(numMatch[2])}</div>
            </div>
          );
        }
      }
      if (trimmed.startsWith('> ')) {
        return (
          <div key={idx} className="my-2.5 p-3 rounded-xl bg-amber-50/80 border-l-4 border-amber-500 text-amber-950 font-medium text-xs leading-relaxed">
            {renderInlineMathAndMarkdown(trimmed.replace(/^>\s*/, ''))}
          </div>
        );
      }
      if (trimmed === '') {
        return <div key={idx} className="h-2" />;
      }
      return (
        <p key={idx} className="my-1.5 text-slate-700 leading-relaxed">
          {renderInlineMathAndMarkdown(trimmed)}
        </p>
      );
    });
  };

  const quickPromptChips = [
    { label: '💡 解釋計量涵義', prompt: '請進一步用淺顯易懂的語言，解構這段內容在計量金融與統計學上的核心實質意涵：' },
    { label: '🐍 提供 Python 代碼', prompt: '請針對上述分析內容，提供完整的 Python (Statsmodels / Scikit-learn) 實作範例代碼：' },
    { label: '📐 深入推導公式', prompt: '請針對這段解析中的計量方程式，提供更完整的逐步數學證明與估計推導：' },
    { label: '📊 台股實證應用', prompt: '請探討此研究方法與指標在台灣股市（加權指數 / 櫃買市場）實務應用上的特徵與調整建議：' },
  ];

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-slate-950/75 backdrop-blur-xs animate-in fade-in duration-200">
      <div 
        className="bg-white rounded-3xl shadow-2xl border border-slate-200 w-full max-w-3xl max-h-[92vh] flex flex-col overflow-hidden text-slate-800 relative"
        onClick={(e) => e.stopPropagation()}
      >
        {/* In-Modal Text Selection Floating Mini-Bar */}
        {modalSelectedText && modalSelectionPos && (
          <div
            id="in-modal-selection-popover"
            style={{
              position: 'fixed',
              left: `${modalSelectionPos.x}px`,
              top: `${modalSelectionPos.y}px`,
              transform: 'translate(-50%, -100%)',
              zIndex: 100,
            }}
            className="animate-in fade-in zoom-in-95 duration-150 bg-slate-900 text-white px-2 py-1.5 rounded-xl shadow-2xl border border-indigo-400/50 backdrop-blur-md flex items-center gap-1 text-xs"
          >
            <button
              onClick={() => handleSpeakSelectedSnippet(modalSelectedText)}
              className="px-2.5 py-1 rounded-lg bg-indigo-600 hover:bg-indigo-700 text-white font-bold flex items-center gap-1.5 transition-colors cursor-pointer shadow-xs"
              title="朗讀所選取的文字"
            >
              <Volume2 className="w-3.5 h-3.5 text-amber-300" />
              <span>朗讀選字</span>
            </button>

            <button
              onClick={() => handleQuoteSelectedTextInInput(modalSelectedText)}
              className="px-2.5 py-1 rounded-lg bg-purple-600 hover:bg-purple-700 text-white font-bold flex items-center gap-1.5 transition-colors cursor-pointer shadow-xs"
              title="將選取文字填入下方提問框進行追問"
            >
              <MessageSquarePlus className="w-3.5 h-3.5 text-purple-200" />
              <span>引用追問</span>
            </button>

            <button
              onClick={() => {
                navigator.clipboard.writeText(modalSelectedText);
                setCopiedSelection(true);
                setTimeout(() => setCopiedSelection(false), 1500);
              }}
              className="p-1 rounded-lg hover:bg-white/10 text-slate-300 hover:text-white transition-colors cursor-pointer"
              title="複製選取文字"
            >
              {copiedSelection ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            </button>

            <button
              onClick={() => {
                setModalSelectedText('');
                setModalSelectionPos(null);
              }}
              className="p-1 rounded-lg hover:bg-white/10 text-slate-400 hover:text-white transition-colors cursor-pointer"
              title="關閉"
            >
              <X className="w-3.5 h-3.5" />
            </button>
          </div>
        )}

        {/* Modal Header */}
        <div className="px-5 sm:px-6 py-4 border-b border-slate-200 bg-gradient-to-r from-indigo-900 via-slate-900 to-purple-950 text-white flex items-center justify-between shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-amber-400 text-slate-950 flex items-center justify-center font-bold shadow-md shrink-0">
              <Sparkles className="w-5 h-5 fill-slate-950" />
            </div>
            <div>
              <div className="flex items-center gap-2 flex-wrap">
                <h2 className="text-sm sm:text-base font-bold text-white">
                  {title}
                </h2>
                <span className="px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-amber-400 text-slate-950 shadow-xs">
                  {stageTitle.split('：')[0] || `階段 ${currentStage}`}
                </span>
                {engineUsed && (
                  <span className="px-2 py-0.5 rounded-full text-[10px] font-bold border flex items-center gap-1 bg-amber-400/20 text-amber-300 border-amber-400/30">
                    <span>{engineUsed}</span>
                    {latencyMs && <span className="font-mono opacity-80">({latencyMs}ms)</span>}
                  </span>
                )}
              </div>
              <p className="text-xs text-indigo-200 flex items-center gap-1.5 mt-0.5">
                <Zap className="w-3.5 h-3.5 text-amber-300" />
                <span>{stageTitle} • 支援滑鼠選字即時朗讀與持續追問</span>
              </p>
            </div>
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={() => {
                if (isSpeaking) onStopSpeech();
                onClose();
              }}
              className="p-2 text-slate-300 hover:text-white hover:bg-white/10 rounded-xl transition-colors cursor-pointer"
              title="關閉視窗"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Modal Body - Scrollable Content Area */}
        <div ref={modalBodyRef} className="p-5 sm:p-6 overflow-y-auto space-y-5 text-xs sm:text-sm flex-1 select-text">
          {/* Original Source Quote */}
          <div className="p-4 rounded-2xl bg-slate-100 border border-slate-200 text-slate-700 space-y-1.5">
            <div className="text-[11px] font-bold uppercase tracking-wider text-slate-500 flex items-center justify-between">
              <span className="flex items-center gap-1.5">
                <BookOpen className="w-3.5 h-3.5 text-indigo-600" />
                <span>您框選的原文段落 / 焦點主題（可滑鼠選字朗讀或追問）</span>
              </span>
              <span className="text-[10px] text-indigo-600 font-normal">提示：選取任意文字即可朗讀或引用</span>
            </div>
            <div className="font-serif italic text-slate-900 leading-relaxed bg-white p-3 rounded-xl border border-slate-200/60 shadow-2xs max-h-32 overflow-y-auto">
              "{sourceText}"
            </div>
          </div>

          {/* Conversation Thread */}
          <div className="space-y-4">
            {messages.map((msg, mIdx) => (
              <div key={mIdx} className={`space-y-2 ${msg.role === 'user' ? 'pl-4 sm:pl-8' : ''}`}>
                <div className="text-xs font-bold text-indigo-950 flex items-center justify-between">
                  <span className="flex items-center gap-1.5">
                    {msg.role === 'ai' ? (
                      <>
                        <Globe className="w-4 h-4 text-indigo-600" />
                        <span>{msg.modelUsed || engineUsed || 'Gemini 2.5 Flash'} 分析結果 (#{mIdx + 1})</span>
                      </>
                    ) : (
                      <>
                        <MessageSquarePlus className="w-4 h-4 text-purple-600" />
                        <span className="text-purple-900">用戶追問探討</span>
                      </>
                    )}
                  </span>
                  {msg.role === 'ai' && !loading && (
                    <div className="flex items-center gap-2">
                      <button
                        onClick={() => {
                          if (isSpeaking) onStopSpeech();
                          else onSpeakText(msg.text);
                        }}
                        className={`px-3 py-1.5 rounded-xl font-semibold text-xs flex items-center gap-1.5 transition-all shadow-xs cursor-pointer ${
                          isSpeaking
                            ? 'bg-rose-600 hover:bg-rose-700 text-white animate-pulse'
                            : 'bg-indigo-600 hover:bg-indigo-700 text-white'
                        }`}
                        title="朗讀整段分析內容"
                      >
                        {isSpeaking ? (
                          <>
                            <VolumeX className="w-3.5 h-3.5" />
                            <span>停止語音</span>
                          </>
                        ) : (
                          <>
                            <Volume2 className="w-3.5 h-3.5" />
                            <span>🔊 全文朗讀</span>
                          </>
                        )}
                      </button>

                      <button
                        onClick={() => handleCopy(msg.text)}
                        className="px-3 py-1.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 font-semibold flex items-center gap-1.5 transition-colors cursor-pointer"
                        title="複製內容"
                      >
                        {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                        <span>{copied ? '已複製' : '複製'}</span>
                      </button>
                    </div>
                  )}
                </div>

                <div className={`p-5 rounded-2xl border leading-relaxed font-sans shadow-inner select-text ${
                  msg.role === 'ai'
                    ? 'bg-gradient-to-br from-indigo-50/50 via-slate-50 to-purple-50/40 border-indigo-100 text-slate-800'
                    : 'bg-purple-50/80 border-purple-200 text-purple-950 font-medium'
                }`}>
                  {msg.role === 'ai' ? renderMarkdown(msg.text) : msg.text}
                </div>
              </div>
            ))}

            {/* Loading Spinner */}
            {(loading || relayLoading) && (
              <div className="py-8 flex flex-col items-center justify-center gap-3 text-slate-500">
                <div className="w-8 h-8 rounded-full border-4 border-indigo-600 border-t-transparent animate-spin" />
                <div className="text-xs font-bold text-indigo-950 animate-pulse">
                  Gemini AI 正在進行接力探討與原創推論...
                </div>
              </div>
            )}
          </div>

          {/* Stage Progression & Dynamic 4 Questions */}
          <div className="space-y-3 pt-3 border-t border-slate-200">
            <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-2">
              <div className="text-xs font-bold text-slate-700 flex items-center gap-1.5 flex-wrap">
                <span className="w-2 h-2 rounded-full bg-indigo-600 animate-pulse" />
                <span className="text-indigo-900 font-extrabold">{stageTitle}</span>
                <span className="text-[10px] font-mono text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded-md border border-indigo-200">
                  AI 每階段推薦 4 題
                </span>
              </div>
              
              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={handleRegenerateCurrentStageQuestions}
                  disabled={questionsLoading || relayLoading}
                  className="px-2.5 py-1 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 text-[11px] font-semibold transition-colors flex items-center gap-1 disabled:opacity-50 cursor-pointer"
                  title="重新為當前階段生成另外 4 個問題"
                >
                  <RefreshCw className={`w-3 h-3 ${questionsLoading ? 'animate-spin' : ''}`} />
                  <span>換一批推薦 (4題)</span>
                </button>
                <button
                  type="button"
                  onClick={handleAdvanceToNextStage}
                  disabled={questionsLoading || relayLoading}
                  className="px-2.5 py-1 rounded-lg bg-indigo-50 hover:bg-indigo-100 text-indigo-700 border border-indigo-200 text-[11px] font-semibold transition-colors flex items-center gap-1 disabled:opacity-50 cursor-pointer"
                  title="跳過當前問題，直接前進下一階段"
                >
                  <span>⏩ 推進下一階段</span>
                </button>
              </div>
            </div>

            {/* Questions Grid (4 questions) */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
              {dynamicRelayQuestions.map((q, qIdx) => (
                <button
                  key={qIdx}
                  type="button"
                  onClick={() => handleSendRelay(q)}
                  disabled={relayLoading || loading || questionsLoading}
                  className="p-3 rounded-2xl bg-gradient-to-r from-purple-50/80 to-indigo-50/80 hover:from-purple-100 hover:to-indigo-100 border border-purple-200/90 text-left text-slate-800 font-medium text-xs transition-all active:scale-98 disabled:opacity-50 cursor-pointer shadow-2xs group flex items-start gap-2"
                >
                  <span className="w-5 h-5 rounded-lg bg-white border border-purple-200 text-purple-700 font-bold flex items-center justify-center text-[10px] shrink-0 mt-0.5 shadow-2xs group-hover:bg-purple-600 group-hover:text-white transition-colors">
                    {qIdx + 1}
                  </span>
                  <span className="leading-snug group-hover:text-indigo-950 font-medium">{q}</span>
                </button>
              ))}
            </div>
            
            {questionsLoading && (
              <div className="text-[11px] text-indigo-600 font-medium flex items-center gap-1.5 animate-pulse pl-1">
                <Sparkles className="w-3.5 h-3.5 text-amber-500" />
                <span>Gemini AI 正在生成下一階段的 4 個深層學術問題...</span>
              </div>
            )}
          </div>
        </div>

        {/* Modal Sticky Footer / Always-Visible Gemini Question Window */}
        <div className="px-5 sm:px-6 py-3.5 border-t border-slate-200 bg-slate-50 shrink-0 sticky bottom-0 z-20 shadow-lg flex flex-col gap-2.5">
          {/* Quick Prompt Chips */}
          <div className="flex items-center gap-1.5 overflow-x-auto pb-1 text-[11px] no-scrollbar">
            <span className="text-slate-400 font-bold shrink-0">快捷提問：</span>
            {quickPromptChips.map((chip, cIdx) => (
              <button
                key={cIdx}
                type="button"
                onClick={() => {
                  setFollowupInput(chip.prompt);
                  if (inputRef.current) inputRef.current.focus();
                }}
                className="px-2.5 py-1 rounded-lg bg-white hover:bg-indigo-50 text-slate-700 hover:text-indigo-700 border border-slate-200 hover:border-indigo-300 font-medium transition-all shrink-0 cursor-pointer shadow-2xs"
              >
                {chip.label}
              </button>
            ))}
          </div>

          {/* Gemini Ask Form */}
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendRelay();
            }}
            className="flex items-center gap-2"
          >
            <div className="relative flex-1">
              <input
                ref={inputRef}
                type="text"
                value={followupInput}
                onChange={(e) => setFollowupInput(e.target.value)}
                placeholder="💬 自由詢問 Gemini 2.5 Flash（支援繁中計量、公式推導、Python代碼，按 Enter 送出）..."
                disabled={relayLoading || loading}
                className="w-full px-4 py-2.5 rounded-xl border border-slate-300 focus:border-indigo-600 focus:ring-2 focus:ring-indigo-100 text-xs sm:text-sm outline-hidden bg-white shadow-inner disabled:opacity-50 pr-8"
              />
              {followupInput && (
                <button
                  type="button"
                  onClick={() => setFollowupInput('')}
                  className="absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-600 p-0.5"
                >
                  <X className="w-3.5 h-3.5" />
                </button>
              )}
            </div>

            <button
              type="submit"
              disabled={relayLoading || loading || !followupInput.trim()}
              className="px-4 py-2.5 bg-gradient-to-r from-indigo-600 via-indigo-700 to-purple-600 hover:from-indigo-700 hover:to-purple-700 text-white font-bold rounded-xl text-xs sm:text-sm transition-all shadow-md flex items-center gap-1.5 disabled:opacity-50 shrink-0 cursor-pointer"
            >
              <Send className="w-4 h-4" />
              <span>{relayLoading ? '思考中...' : '詢問 Gemini'}</span>
            </button>
          </form>

          <div className="flex items-center justify-between text-[11px] text-slate-500">
            <div className="flex items-center gap-1.5">
              <span className="w-2 h-2 rounded-full bg-emerald-500 animate-pulse" />
              <span>Gemini 2.5 Flash 接力對話中 • 所有追問已自動同步至 Firebase</span>
            </div>
            <button
              type="button"
              onClick={() => {
                if (isSpeaking) onStopSpeech();
                onClose();
              }}
              className="px-3 py-1 bg-slate-200 hover:bg-slate-300 text-slate-700 font-medium rounded-lg transition-colors cursor-pointer"
            >
              關閉視窗
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
